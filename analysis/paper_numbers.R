## writes numbers/paper_numbers.md (all tables) and one CSV per table. Read
## the results from VC_RESULTS (default results/).
## Conventions: increments over the paired no-interaction control; each
## estimator at its best basis among five in each setting; "% > 0" is the
## proportion of settings (or cells) where a difference is positive; ci is the
## half-width of the 95 % interval across settings (or replicates).
source("analysis/read_results.R")
OUT <- "numbers"
dir.create(OUT, showWarnings = FALSE)
MD <- file.path(OUT, "paper_numbers.md")
cat("# Numbers of the paper\n\n",
    "Generated by `analysis/paper_numbers.R` on ", format(Sys.Date()), ". Do not edit: rerun the script.\n\n",
    sep = "", file = MD)

f3 <- function(x) sprintf("%+.3f", x)
pct <- function(x) sprintf("%.0f %%", 100 * x)
ci <- function(x) { x <- x[is.finite(x)]; if (length(x) < 3) NA else qt(0.975, length(x) - 1) * sd(x) / sqrt(length(x)) }
md_table <- function(df) {
  df[] <- lapply(df, function(v) if (is.numeric(v)) sprintf("%.3f", v) else as.character(v))
  c(paste0("| ", paste(names(df), collapse = " | "), " |"),
    paste0("|", paste(rep("---", ncol(df)), collapse = "|"), "|"),
    apply(df, 1, function(r) paste0("| ", paste(r, collapse = " | "), " |")))
}
emit <- function(id, title, note, df) {
  write.csv(df, file.path(OUT, paste0(id, ".csv")), row.names = FALSE)
  cat(sprintf("## %s. %s\n\n%s\n\n", id, title, note), file = MD, append = TRUE)
  cat(md_table(df), sep = "\n", file = MD, append = TRUE); cat("\n\n", file = MD, append = TRUE)
  message(id, ": ", nrow(df), " rows")
}
summ <- function(d, by, value = "d") {
  a <- aggregate(d[[value]], d[by], function(v) c(mean = mean(v, na.rm = TRUE), pos = mean(v > 0, na.rm = TRUE), ci = ci(v)))
  cbind(a[by], mean = f3(a$x[, "mean"]), `% > 0` = pct(a$x[, "pos"]), ci = sprintf("%.3f", a$x[, "ci"]))
}
