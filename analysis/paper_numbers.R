E.BASES <- c("cat.2", "poly.3", "spline.2"); E.METRICS <- c("AUC_competition", "precision_k_competition")
e_read <- function(camp, stem) do.call(rbind, lapply(c("lottery", "dynamics"), function(g) {
  d <- load_grid(paste0(stem, g), camp)
  d$mech <- if (g == "lottery") "lottery" else d$dynamics
  d$base <- basis_of(d$method)
  keep <- d$interaction.threshold == 10 & d$niche.breadth %in% c(5, 10, 20) & d$base %in% E.BASES
  keep <- keep & if (g == "lottery") d$competition.intensity == 2 else d$dyn.strength == 0.5 & d$dyn.sigma == 0.5
  d[keep, c("method", "fam", "arm", "simu", "niche.breadth", "mech", "base", E.METRICS, paste0(E.METRICS, "_alt"))] }))
e_cells <- function(x, alt, name) do.call(rbind, lapply(E.METRICS, function(m) {
  k <- function(z) paste(z$mech, z$niche.breadth, z$base, z$simu)
  A <- x[x$arm == "interactions", ]; B <- x[x$arm == "no.interaction", ]
  z <- data.frame(mech = A$mech, b = A$niche.breadth, base = A$base,
                  inc = A[[paste0(m, alt)]] - B[[paste0(m, alt)]][match(k(A), k(B))])
  a <- aggregate(inc ~ mech + b + base, z[is.finite(z$inc), ], mean)
  a <- do.call(rbind, lapply(split(a, list(a$mech, a$b), drop = TRUE), function(s) s[which.max(s$inc), ]))
  aggregate(inc ~ mech, data.frame(a, metric = m), mean) |> transform(metric = m, estimator = name) }))
